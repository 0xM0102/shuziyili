def main() -> None:
    out = []
    seen = set()
    for adcode, name, province, lat, lng in CITIES:
        if adcode in seen:
            continue
        seen.add(adcode)
        out.append({
            "adcode": adcode,
            "name": name,
            "province": province,
            "lat": lat,
            "lng": lng,
            "featured": adcode in ILI_ADCODES,
        })

    target = Path(__file__).resolve().parents[1] / "src/main/resources/weather/region-catalog.json"
    target.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    featured = sum(1 for x in out if x["featured"])
    print(f"Wrote {len(out)} regions ({featured} featured) -> {target}")


if __name__ == "__main__":
    main()
